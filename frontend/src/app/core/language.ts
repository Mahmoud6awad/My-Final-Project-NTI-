@Injectable({ providedIn: 'root' })
export class LanguageService {
  readonly current = signal<Language>(this.readLanguage());

  constructor(@Inject(DOCUMENT) private readonly document: Document) {
    this.applyDirection(this.current());
  }

  toggle(): void {
    const language = this.current() === 'en' ? 'ar' : 'en';
    this.current.set(language);
    this.applyDirection(language);
    try {
      localStorage.setItem('nova-language', language);
    } catch {
      // The current selection still applies for this page view.
    }
  }

  translate(value: string): string {
    if (this.current() !== 'ar') return value;
    const availableCount = /^(\d+) available$/.exec(value);
    if (availableCount) return `متاح: ${availableCount[1]}`;
    return arabicTranslations[value] ?? value;
  }

  private readLanguage(): Language {
    try {
      return localStorage.getItem('nova-language') === 'ar' ? 'ar' : 'en';
    } catch {
      return 'en';
    }
  }

  private applyDirection(language: Language): void {
    this.document.documentElement.lang = language;
    this.document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    this.document.title = language === 'ar' ? 'متجر نوفا' : 'Nova Store';
  }
}

@Pipe({ name: 'translate', standalone: true, pure: false })
export class TranslatePipe implements PipeTransform {
  constructor(private readonly language: LanguageService) {}

  transform(value: string): string {
    return this.language.translate(value);
  }
}
